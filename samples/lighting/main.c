/*
 * ps2vk lighting sample: a slowly turning sphere lit by a directional light
 * that orbits it. The camera matrix and the light live in two uniform buffers
 * in one descriptor set; the light's buffer is rewritten every frame, and the
 * draw reads it when the command buffer is submitted. The model rotation and
 * material color are push constants. The vertex shader computes the dot
 * product of normal and light per vertex; the lit intensity comes from a ramp
 * texture the GS looks up per pixel, so the day/night line stays a clean curve.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ps2vk.h"

/* Generated by ps2vk-shaderc from lighting.vert / lighting.frag. */
extern const PvkShaderCode lighting_vert;
extern const PvkShaderCode lighting_frag;

#define WIDTH  640
#define HEIGHT 448

#define CHECK(call)                                                       \
    do {                                                                  \
        PvkResult res_ = (call);                                          \
        if (res_ != PVK_SUCCESS) {                                        \
            printf("lighting: %s failed (%d)\n", #call, (int)res_);       \
            return 1;                                                     \
        }                                                                 \
    } while (0)

/* One vertex: position and normal, each a vec4. */
typedef struct {
    float pos[4];
    float normal[4];
} Vertex;

/* The uniform blocks, laid out as the shader declares them (std140). */
typedef struct {
    float viewProj[16];
} Camera;

typedef struct {
    float direction[4];
    float color[4];
} Light;

/* The push constant block. */
typedef struct {
    float model[16];
    float material[4];
} Push;

/* The lighting ramp: texel x holds the intensity for dot product
 * (x / 255 - 0.5) / 0.49609375, the inverse of the vertex shader's mapping,
 * clamped below at the ambient level. GS modulate treats 0x80 as 1.0, so the
 * ramp tops out there and the vertex color is multiplied by at most 1. */
#define RAMP_WIDTH  256
#define RAMP_HEIGHT 8
#define AMBIENT     0.1f

static void build_ramp(uint32_t *pixels)
{
    for (int x = 0; x < RAMP_WIDTH; x++) {
        float d = ((float)x / (RAMP_WIDTH - 1) - 0.5f) / 0.49609375f;
        float v = AMBIENT + (1.0f - AMBIENT) * (d > 0.0f ? (d < 1.0f ? d : 1.0f) : 0.0f);
        uint32_t c = (uint32_t)(v * 128.0f + 0.5f);
        for (int y = 0; y < RAMP_HEIGHT; y++)
            pixels[y * RAMP_WIDTH + x] = 0x80000000u | (c << 16) | (c << 8) | c;
    }
}

/* A unit sphere of RINGS bands of SEGMENTS quads, two triangles each. The
 * normal of a unit sphere's point is the point itself. */
#define RINGS    32
#define SEGMENTS 64
#define VERTEX_COUNT ((RINGS + 1) * (SEGMENTS + 1))
#define INDEX_COUNT  (RINGS * SEGMENTS * 6)

static void build_sphere(Vertex *v, uint16_t *idx)
{
    for (int r = 0; r <= RINGS; r++) {
        float phi = 3.14159265f * (float)r / RINGS;   /* 0 at the top, pi at the bottom */
        for (int s = 0; s <= SEGMENTS; s++) {
            float theta = 2.0f * 3.14159265f * (float)s / SEGMENTS;
            Vertex *p = &v[r * (SEGMENTS + 1) + s];
            p->pos[0] = sinf(phi) * cosf(theta);
            p->pos[1] = cosf(phi);
            p->pos[2] = sinf(phi) * sinf(theta);
            p->pos[3] = 1.0f;
            p->normal[0] = p->pos[0];
            p->normal[1] = p->pos[1];
            p->normal[2] = p->pos[2];
            p->normal[3] = 0.0f;
        }
    }
    for (int r = 0; r < RINGS; r++) {
        for (int s = 0; s < SEGMENTS; s++) {
            uint16_t a = (uint16_t)(r * (SEGMENTS + 1) + s), b = (uint16_t)(a + SEGMENTS + 1);
            uint16_t *t = idx + (r * SEGMENTS + s) * 6;
            t[0] = a; t[1] = b;     t[2] = a + 1;
            t[3] = b; t[4] = b + 1; t[5] = a + 1;
        }
    }
}

/* Column-major 4x4 matrices: m[col * 4 + row]. */
static void mat_identity(float *m)
{
    memset(m, 0, 16 * sizeof(float));
    m[0] = m[5] = m[10] = m[15] = 1.0f;
}

static void mat_mul(float *out, const float *a, const float *b)
{
    float r[16];
    for (int c = 0; c < 4; c++)
        for (int rw = 0; rw < 4; rw++) {
            float s = 0.0f;
            for (int k = 0; k < 4; k++)
                s += a[k * 4 + rw] * b[c * 4 + k];
            r[c * 4 + rw] = s;
        }
    memcpy(out, r, sizeof(r));
}

static void mat_rotate_y(float *m, float angle)
{
    mat_identity(m);
    m[0] = cosf(angle);  m[8]  = sinf(angle);
    m[2] = -sinf(angle); m[10] = cosf(angle);
}

static void mat_rotate_x(float *m, float angle)
{
    mat_identity(m);
    m[5] = cosf(angle); m[9]  = -sinf(angle);
    m[6] = sinf(angle); m[10] = cosf(angle);
}

static void mat_translate(float *m, float x, float y, float z)
{
    mat_identity(m);
    m[12] = x; m[13] = y; m[14] = z;
}

/* Vulkan clip space: y points down, depth 0 (near) to 1 (far). */
static void mat_perspective(float *m, float fovY, float aspect, float near, float far)
{
    float f = 1.0f / tanf(fovY * 0.5f);
    memset(m, 0, 16 * sizeof(float));
    m[0]  = f / aspect;
    m[5]  = -f;
    m[10] = far / (near - far);
    m[11] = -1.0f;
    m[14] = near * far / (near - far);
}

int main(void)
{
    PvkInstance instance;
    PvkDevice device;
    PvkQueue queue;
    PvkSwapchain swapchain;
    PvkImage images[2], depth, ramp;
    PvkImageView views[2], depthView, rampView;
    PvkSampler rampSampler;
    uint32_t imageCount = 2;
    PvkBuffer vertexBuffer, indexBuffer, cameraBuffer, lightBuffer, rampBuffer;
    PvkShaderModule vs, fs;
    PvkDescriptorSetLayout setLayout;
    PvkDescriptorPool descriptorPool;
    PvkDescriptorSet descriptorSet;
    PvkPipelineLayout layout;
    PvkPipeline pipeline;
    PvkCommandBuffer cmd;
    PvkFence fence;
    void *mapped;
    Camera *camera;
    Light *light;
    static Vertex vertices[VERTEX_COUNT];
    static uint16_t indices[INDEX_COUNT];
    float proj[16], view[16];

    build_sphere(vertices, indices);

    PvkInstanceCreateInfo instanceInfo = { .applicationName = "lighting" };
    CHECK(pvkCreateInstance(&instanceInfo, &instance));
    CHECK(pvkCreateDevice(instance, NULL, &device));
    pvkGetDeviceQueue(device, &queue);

    PvkSwapchainCreateInfo swapchainInfo = {
        .width = WIDTH, .height = HEIGHT, .format = PVK_FORMAT_CT32, .imageCount = 2,
        .displayMode = PVK_DISPLAY_MODE_NTSC,
    };
    CHECK(pvkCreateSwapchain(device, &swapchainInfo, &swapchain));
    CHECK(pvkGetSwapchainImages(device, swapchain, &imageCount, images));
    for (uint32_t i = 0; i < imageCount; i++) {
        PvkImageViewCreateInfo viewInfo = { .image = images[i], .levelCount = 1 };
        CHECK(pvkCreateImageView(device, &viewInfo, &views[i]));
    }

    /* VRAM is handed out in order: framebuffers, then the depth buffer, then the ramp. */
    PvkImageCreateInfo depthInfo = { .width = WIDTH, .height = HEIGHT, .format = PVK_FORMAT_Z24 };
    CHECK(pvkCreateImage(device, &depthInfo, &depth));
    PvkImageCreateInfo rampInfo = { .width = RAMP_WIDTH, .height = RAMP_HEIGHT, .format = PVK_FORMAT_CT32 };
    CHECK(pvkCreateImage(device, &rampInfo, &ramp));
    PvkImageViewCreateInfo depthViewInfo = { .image = depth, .levelCount = 1 };
    CHECK(pvkCreateImageView(device, &depthViewInfo, &depthView));
    PvkImageViewCreateInfo rampViewInfo = { .image = ramp, .levelCount = 1 };
    CHECK(pvkCreateImageView(device, &rampViewInfo, &rampView));
    /* Clamp to edge: a dot product past either end of the ramp reads its end
     * texel instead of wrapping round to the other end. */
    PvkSamplerCreateInfo rampSamplerInfo = {
        .magFilter = PVK_FILTER_LINEAR, .minFilter = PVK_FILTER_LINEAR,
        .addressModeU = PVK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE, .addressModeV = PVK_SAMPLER_ADDRESS_MODE_CLAMP_TO_EDGE,
    };
    CHECK(pvkCreateSampler(device, &rampSamplerInfo, &rampSampler));

    PvkBufferCreateInfo bufferInfo = { .size = sizeof(vertices) };
    CHECK(pvkCreateBuffer(device, &bufferInfo, &vertexBuffer));
    CHECK(pvkMapMemory(device, vertexBuffer, &mapped));
    memcpy(mapped, vertices, sizeof(vertices));
    pvkUnmapMemory(device, vertexBuffer);

    PvkBufferCreateInfo indexInfo = { .size = sizeof(indices) };
    CHECK(pvkCreateBuffer(device, &indexInfo, &indexBuffer));
    CHECK(pvkMapMemory(device, indexBuffer, &mapped));
    memcpy(mapped, indices, sizeof(indices));
    pvkUnmapMemory(device, indexBuffer);

    /* The camera is written once; the light stays mapped and is rewritten
     * every frame before the draw is recorded. */
    PvkBufferCreateInfo cameraInfo = { .size = sizeof(Camera) };
    CHECK(pvkCreateBuffer(device, &cameraInfo, &cameraBuffer));
    CHECK(pvkMapMemory(device, cameraBuffer, &mapped));
    camera = mapped;
    mat_perspective(proj, 60.0f * 3.14159265f / 180.0f, 4.0f / 3.0f, 0.5f, 10.0f); /* the display is 4:3 */
    mat_translate(view, 0.0f, 0.0f, -3.5f);
    mat_mul(camera->viewProj, proj, view);
    pvkUnmapMemory(device, cameraBuffer);

    PvkBufferCreateInfo lightInfo = { .size = sizeof(Light) };
    CHECK(pvkCreateBuffer(device, &lightInfo, &lightBuffer));
    CHECK(pvkMapMemory(device, lightBuffer, &mapped));
    light = mapped;
    memset(light, 0, sizeof(*light));
    light->color[0] = 1.0f; light->color[1] = 0.95f; light->color[2] = 0.85f; light->color[3] = 1.0f;

    /* The ramp's pixels: a staging buffer, uploaded once below. */
    PvkBufferCreateInfo rampBufferInfo = { .size = RAMP_WIDTH * RAMP_HEIGHT * 4 };
    CHECK(pvkCreateBuffer(device, &rampBufferInfo, &rampBuffer));
    CHECK(pvkMapMemory(device, rampBuffer, &mapped));
    build_ramp(mapped);
    pvkUnmapMemory(device, rampBuffer);

    PvkShaderModuleCreateInfo vsInfo = { .code = &lighting_vert };
    PvkShaderModuleCreateInfo fsInfo = { .code = &lighting_frag };
    CHECK(pvkCreateShaderModule(device, &vsInfo, &vs));
    CHECK(pvkCreateShaderModule(device, &fsInfo, &fs));

    PvkVertexInputBinding binding = { .binding = 0, .stride = sizeof(Vertex) };
    size_t noOffset = 0;
    PvkVertexInputAttribute attributes[] = {
        { .location = 0, .format = PVK_FORMAT_R32G32B32A32_SFLOAT, .offset = 0 },
        { .location = 1, .format = PVK_FORMAT_R32G32B32A32_SFLOAT, .offset = 16 },
    };

    /* Set 0: the camera at binding 0 and the light at binding 1, read by the
     * vertex shader; the ramp at binding 2, sampled by the fragment shader. */
    PvkDescriptorSetLayoutBinding bindings[] = {
        { .binding = 0, .descriptorType = PVK_DESCRIPTOR_TYPE_UNIFORM_BUFFER,
          .descriptorCount = 1, .stageFlags = PVK_SHADER_STAGE_VERTEX },
        { .binding = 1, .descriptorType = PVK_DESCRIPTOR_TYPE_UNIFORM_BUFFER,
          .descriptorCount = 1, .stageFlags = PVK_SHADER_STAGE_VERTEX },
        { .binding = 2, .descriptorType = PVK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER,
          .descriptorCount = 1, .stageFlags = PVK_SHADER_STAGE_FRAGMENT },
    };
    PvkDescriptorSetLayoutCreateInfo setLayoutInfo = { .bindingCount = 3, .bindings = bindings };
    CHECK(pvkCreateDescriptorSetLayout(device, &setLayoutInfo, &setLayout));

    PvkPushConstantRange pushRange = { .stageFlags = PVK_SHADER_STAGE_VERTEX, .offset = 0, .size = sizeof(Push) };
    PvkPipelineLayoutCreateInfo layoutInfo = {
        .setLayoutCount = 1, .setLayouts = &setLayout,
        .pushConstantRangeCount = 1, .pushConstantRanges = &pushRange,
    };
    CHECK(pvkCreatePipelineLayout(device, &layoutInfo, &layout));

    PvkDescriptorPoolSize poolSizes[] = {
        { .type = PVK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, .descriptorCount = 2 },
        { .type = PVK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, .descriptorCount = 1 },
    };
    PvkDescriptorPoolCreateInfo poolInfo = { .maxSets = 1, .poolSizeCount = 2, .poolSizes = poolSizes };
    CHECK(pvkCreateDescriptorPool(device, &poolInfo, &descriptorPool));
    PvkDescriptorSetAllocateInfo setInfo = {
        .descriptorPool = descriptorPool, .descriptorSetCount = 1, .setLayouts = &setLayout,
    };
    CHECK(pvkAllocateDescriptorSets(device, &setInfo, &descriptorSet));
    PvkDescriptorBufferInfo cameraDescriptor = { .buffer = cameraBuffer, .offset = 0, .range = PVK_WHOLE_SIZE };
    PvkDescriptorBufferInfo lightDescriptor  = { .buffer = lightBuffer,  .offset = 0, .range = PVK_WHOLE_SIZE };
    PvkDescriptorImageInfo rampDescriptor = { .sampler = rampSampler, .imageView = rampView };
    PvkWriteDescriptorSet writes[] = {
        { .dstSet = descriptorSet, .dstBinding = 0,
          .descriptorType = PVK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, .bufferInfo = &cameraDescriptor },
        { .dstSet = descriptorSet, .dstBinding = 1,
          .descriptorType = PVK_DESCRIPTOR_TYPE_UNIFORM_BUFFER, .bufferInfo = &lightDescriptor },
        { .dstSet = descriptorSet, .dstBinding = 2,
          .descriptorType = PVK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER, .imageInfo = &rampDescriptor },
    };
    pvkUpdateDescriptorSets(device, 3, writes);

    PvkGraphicsPipelineCreateInfo pipelineInfo = {
        .vertexShader   = vs,
        .fragmentShader = fs,
        .layout         = layout,
        .bindingCount   = 1,
        .bindings       = &binding,
        .attributeCount = 2,
        .attributes     = attributes,
        .topology       = PVK_PRIMITIVE_TOPOLOGY_TRIANGLE_LIST,
        .viewport       = { 0.0f, 0.0f, WIDTH, HEIGHT, 0.0f, 1.0f },
        .depthAttachmentFormat = PVK_FORMAT_Z24,
        .depthStencil   = { .depthTestEnable = 1, .depthWriteEnable = 1, .depthCompareOp = PVK_COMPARE_OP_LESS },
    };
    CHECK(pvkCreateGraphicsPipeline(device, &pipelineInfo, &pipeline));

    CHECK(pvkCreateCommandBuffer(device, NULL, &cmd));
    CHECK(pvkCreateFence(device, NULL, &fence));

    /* Upload the ramp once, outside rendering, and wait for it. */
    CHECK(pvkBeginCommandBuffer(cmd));
    PvkBufferImageCopy copy = { .bufferOffset = 0, .rect = { 0, 0, RAMP_WIDTH, RAMP_HEIGHT } };
    pvkCmdCopyBufferToImage(cmd, rampBuffer, ramp, &copy);
    CHECK(pvkEndCommandBuffer(cmd));
    CHECK(pvkQueueSubmit(queue, cmd, fence));
    CHECK(pvkWaitForFences(device, 1, &fence));

    printf("lighting: running\n");

    for (unsigned frame = 0;; frame++) {
        uint32_t imageIndex;
        float ry[16], rx[16], orbit;
        Push push = { .material = { 0.9f, 0.5f, 0.3f, 1.0f } };

        mat_rotate_y(ry, (float)frame * 0.01f);
        mat_rotate_x(rx, 0.4f);
        mat_mul(push.model, rx, ry);   /* spin about y, tilted towards the camera */

        /* The light circles the sphere once every 600 frames, a little above it. */
        orbit = (float)frame * 2.0f * 3.14159265f / 600.0f;
        light->direction[0] = cosf(orbit) * 0.8f;
        light->direction[1] = 0.6f;
        light->direction[2] = sinf(orbit) * 0.8f;

        CHECK(pvkAcquireNextImage(device, swapchain, &imageIndex));

        CHECK(pvkBeginCommandBuffer(cmd));
        PvkRenderingInfo rendering = {
            .renderArea = { 0, 0, WIDTH, HEIGHT },
            .colorAttachment = {
                .imageView  = views[imageIndex],
                .loadOp     = PVK_ATTACHMENT_LOAD_OP_CLEAR,
                .clearValue = { .color = { { 0.05f, 0.05f, 0.1f, 1.0f } } },
            },
            .depthAttachment = {
                .imageView  = depthView,
                .loadOp     = PVK_ATTACHMENT_LOAD_OP_CLEAR,
                .clearValue = { .depthStencil = { .depth = 1.0f } },
            },
        };
        pvkCmdBeginRendering(cmd, &rendering);
        pvkCmdBindPipeline(cmd, pipeline);
        pvkCmdBindDescriptorSets(cmd, layout, 0, 1, &descriptorSet);
        pvkCmdPushConstants(cmd, layout, PVK_SHADER_STAGE_VERTEX, 0, sizeof(push), &push);
        pvkCmdBindVertexBuffers(cmd, 0, 1, &vertexBuffer, &noOffset);
        pvkCmdBindIndexBuffer(cmd, indexBuffer, 0, PVK_INDEX_TYPE_UINT16);
        pvkCmdDrawIndexed(cmd, INDEX_COUNT, 0, 0);
        pvkCmdEndRendering(cmd);
        CHECK(pvkEndCommandBuffer(cmd));

        CHECK(pvkResetFences(device, 1, &fence));
        CHECK(pvkQueueSubmit(queue, cmd, fence));
        CHECK(pvkWaitForFences(device, 1, &fence));
        CHECK(pvkQueuePresent(queue, swapchain, imageIndex));
    }

    return 0;
}
